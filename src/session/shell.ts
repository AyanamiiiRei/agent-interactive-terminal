/**
 * Shell launch strategy.
 *
 * A generated rcfile loads the user's own configuration first and then
 * installs private prompt markers. Installing markers *after* the user's rc
 * matters: a custom PS1 that runs later would otherwise erase them, which is
 * exactly the case that makes ready detection degrade to guessing.
 *
 * @module agent-interactive-terminal/session/shell
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, join } from 'node:path'

export interface ShellLaunch {
  file: string
  args: string[]
  /** Directory of generated files to remove when the session closes. */
  cleanup(): void
}

const BASH_RC = `# Generated by agent-interactive-terminal.
# Load the user's configuration, then install private prompt markers.
if [ -f "$HOME/.bashrc" ]; then
  . "$HOME/.bashrc"
fi

__ait_prev_pc="\${PROMPT_COMMAND-}"
PROMPT_COMMAND='__ait_status=$?; printf "\\033]9999;D;%d\\007" "$__ait_status"; printf "\\033]7;file://%s%s\\007" "\${HOSTNAME-}" "$PWD"'
if [ -n "$__ait_prev_pc" ]; then
  PROMPT_COMMAND="$PROMPT_COMMAND; $__ait_prev_pc"
fi

if [ -z "\${PS1-}" ]; then
  PS1='\\$ '
fi
PS1='\\[\\033]9999;A\\007\\]'"$PS1"'\\[\\033]9999;B\\007\\]'
`

/** Choose the shell to run, preferring an explicit path, then `$SHELL`. */
export function resolveShell(explicit?: string): string {
  if (explicit && explicit.length > 0) return explicit
  const fromEnv = process.env.SHELL
  if (fromEnv && fromEnv.startsWith('/')) return fromEnv
  return '/bin/bash'
}

/** Build the executable, arguments, and any generated startup files. */
export function buildShellLaunch(shell: string): ShellLaunch {
  const name = basename(shell)
  if (name === 'bash') {
    const dir = mkdtempSync(join(tmpdir(), 'ait-rc-'))
    const rcfile = join(dir, 'bashrc')
    writeFileSync(rcfile, BASH_RC, { mode: 0o600 })
    return {
      file: shell,
      args: ['--rcfile', rcfile, '-i'],
      cleanup: () => rmSync(dir, { recursive: true, force: true }),
    }
  }
  return { file: shell, args: ['-i'], cleanup: () => {} }
}
